// Writes the USDA SR Legacy seed migration from the unzipped FoodData Central CSV directory.
// Usage: npx tsx scripts/usda/build-seed.ts <csv-dir> [migration.sql]
// See scripts/usda/README.md.
import { createReadStream, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createInterface } from 'node:readline';
import {
	NUTRIENT_IDS,
	parseCsvLine,
	seedSql,
	unitsForPortions,
	type UsdaFood,
	type UsdaPortion
} from '../../src/lib/domain/usda-seed';

const [dir, target] = process.argv.slice(2);
if (!dir) {
	console.error('Usage: npx tsx scripts/usda/build-seed.ts <csv-dir> [migration.sql]');
	process.exit(1);
}

/** Rows of a CSV file as objects keyed by the header line. */
async function* rows(file: string) {
	const lines = createInterface({ input: createReadStream(join(dir, file), 'utf8') });
	let header: string[] | null = null;
	for await (const line of lines) {
		if (!line) continue;
		const fields = parseCsvLine(line);
		if (!header) header = fields;
		else yield Object.fromEntries(header.map((h, i) => [h, fields[i] ?? '']));
	}
}

const foods = new Map<string, UsdaFood>();
for await (const r of rows('food.csv')) {
	foods.set(r.fdc_id, {
		fdcId: r.fdc_id,
		name: r.description.trim(),
		kcal: 0,
		protein: 0,
		carbs: 0,
		fat: 0
	});
}

const field = Object.fromEntries(Object.entries(NUTRIENT_IDS).map(([k, id]) => [id, k])) as Record<
	string,
	'kcal' | 'protein' | 'carbs' | 'fat'
>;
for await (const r of rows('food_nutrient.csv')) {
	const key = field[r.nutrient_id];
	const food = foods.get(r.fdc_id);
	const amount = Number(r.amount);
	if (key && food && Number.isFinite(amount) && amount >= 0) food[key] = amount;
}

const portions = new Map<string, UsdaPortion[]>();
for await (const r of rows('food_portion.csv')) {
	if (!foods.has(r.fdc_id)) continue;
	const list = portions.get(r.fdc_id) ?? [];
	list.push({
		fdcId: r.fdc_id,
		seq: Number(r.seq_num) || 0,
		amount: Number(r.amount),
		modifier: r.modifier || r.portion_description,
		gramWeight: Number(r.gram_weight)
	});
	portions.set(r.fdc_id, list);
}

const units = new Map([...portions].map(([id, list]) => [id, unitsForPortions(list)]));
const sql = seedSql([...foods.values()], units);

const file =
	target ??
	join(
		'drizzle',
		readdirSync('drizzle').find((f) => f.endsWith('_usda_sr_legacy.sql')) ??
			(() => {
				throw new Error('Run `npx drizzle-kit generate --custom --name usda_sr_legacy` first.');
			})()
	);
const header =
	'-- USDA FoodData Central SR Legacy (FoodData_Central_sr_legacy_food_csv_2018-04), public domain.\n' +
	'-- Generated by scripts/usda/build-seed.ts. Do not edit by hand.\n';
writeFileSync(file, header + sql);
const unitCount = [...units.values()].reduce((n, u) => n + u.length, 0);
console.log(
	`Wrote ${file}: ${foods.size} foods, ${unitCount} units, ${readFileSync(file).length} bytes.`
);
